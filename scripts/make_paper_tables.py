#!/usr/bin/env python3
"""Generate paper-ready result tables directly from frozen JSON artifacts."""

import argparse
import ast
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
DEFAULT_CLEAN_LOG = RESULTS / "2026-10-31-11-23-31-784610" / "log.txt"


def load_json(name):
    with (RESULTS / name).open("r", encoding="utf-8") as handle:
        return json.load(handle)


def read_clean_metrics(path):
    pattern = re.compile(r"^average:\s*(\{.*\})\s*$")
    matches = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            match = pattern.match(line.strip())
            if match:
                matches.append(ast.literal_eval(match.group(1)))
    if not matches:
        raise ValueError(f"no average metric line found in {path}")
    return matches[-1]


def pct(value, digits=1):
    return f"{100.0 * float(value):.{digits}f}%"


def number(value, digits=3):
    return f"{float(value):.{digits}f}"


def threshold_range(value):
    if isinstance(value, (list, tuple)):
        values = [float(item) for item in value]
    else:
        values = [float(item) for item in str(value).strip("[]").replace(",", " ").split()]
    return f"{min(values):.2f}-{max(values):.2f}"


def build_tables(clean_log):
    clean = read_clean_metrics(clean_log)
    vq_user = load_json("user_fingerprint_eval_30k_min11.json")
    sim_user = load_json("user_fingerprint_eval_30k_min11_simswap224_probs.json")
    ins_user = load_json("user_fingerprint_eval_30k_min11_inswapper128_probs.json")
    vq_multi = load_json("multimage_llr_summary.json")
    sim_multi = load_json("simswap224_multimage_llr_summary.json")
    ins_multi = load_json("inswapper128_multimage_llr_summary.json")
    vq_collusion = load_json("vqgan_collusion_soft_detector_mean_100groups.json")
    sim_collusion = load_json("simswap224_collusion_mix_summary.json")
    ins_collusion_pilot = load_json("inswapper128_collusion_mix_10groups_exploratory.json")
    threshold_cv = load_json("collusion_threshold_cv.json")
    vq_500 = load_json("user_fingerprint_eval_30k_500users_bch_vqgan_probs.json")
    sim_500 = load_json("user_fingerprint_eval_30k_500users_bch_simswap224_probs.json")
    ins_500 = load_json("user_fingerprint_eval_30k_500users_bch_inswapper128_probs.json")
    vq_scale = load_json("codebook_scaling_500users.json")
    sim_scale = load_json("codebook_scaling_500users_simswap224.json")
    ins_scale = load_json("codebook_scaling_500users_inswapper128.json")

    lines = [
        "# DiffMark paper result tables",
        "",
        "This file is generated by `scripts/make_paper_tables.py` from frozen JSON/log artifacts. Do not hand-edit the tables.",
        "",
        "## Table 1a. Clean watermark quality",
        "",
        "| Condition | Images | PSNR (dB) | SSIM | LPIPS | BER |",
        "|---|---:|---:|---:|---:|---:|",
        f"| Clean watermark | 500 | {number(clean['psnr'], 4)} | {number(clean['ssim'], 4)} | "
        f"{number(clean['lpips'], 5)} | {pct(clean['ber'], 3)} |",
        "",
        "## Table 1b. Single-image user-code decoding",
        "",
        "| Attack | Images | BER | Exact 30-bit | Mean Hamming | Max Hamming | Top-1 (100 users) | Second-best Hamming margin (100 users) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, data in (
        ("VQGAN", vq_user),
        ("SimSwap-224", sim_user),
        ("InSwapper-128", ins_user),
    ):
        per_image = data["per_image"]
        final = data["final"]
        lines.append(
            f"| {name} | 500 | {pct(per_image['ber'], 4)} | {pct(per_image['exact_match'], 1)} | "
            f"{number(per_image['mean_hamming'], 3)} | {int(per_image['max_hamming'])} | "
            f"{pct(final['user_identification_accuracy'], 1)} | {number(final['mean_second_best_margin'], 3)} |"
        )

    lines.extend(
        [
            "",
            "The single-image evaluation uses 100 users x 5 images. The 500-user, one-image-per-user results are reported separately in Table 6.",
            "",
            "## Table 2. Multi-image evidence aggregation",
            "",
            "| Images m | VQGAN LLR z | VQGAN prob-avg z | SimSwap LLR z | SimSwap prob-avg z | InSwapper LLR z | InSwapper prob-avg z | Top-1 | Z=6 detection (VQ / Sim / InSw) |",
            "|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for m in range(1, 6):
        vq_llr = vq_multi["summary"][str(m)]["llr"]
        vq_prob = vq_multi["summary"][str(m)]["mean_prob"]
        sim_llr = sim_multi["summary"][str(m)]["llr"]
        sim_prob = sim_multi["summary"][str(m)]["mean_prob"]
        ins_llr = ins_multi["summary"][str(m)]["llr"]
        ins_prob = ins_multi["summary"][str(m)]["mean_prob"]
        vq_detect = vq_llr["thresholds"]["6.0"]["detect"]
        sim_detect = sim_llr["thresholds"]["6.0"]["detect"]
        ins_detect = ins_llr["thresholds"]["6.0"]["detect"]
        top1 = min(vq_llr["top1"], sim_llr["top1"], ins_llr["top1"])
        lines.append(
            f"| {m} | {number(vq_llr['mean_true_z'], 3)} | {number(vq_prob['mean_true_z'], 3)} | "
            f"{number(sim_llr['mean_true_z'], 3)} | {number(sim_prob['mean_true_z'], 3)} | "
            f"{number(ins_llr['mean_true_z'], 3)} | {number(ins_prob['mean_true_z'], 3)} | "
            f"{pct(top1, 1)} | {pct(vq_detect, 0)} / {pct(sim_detect, 0)} / "
            f"{pct(ins_detect, 0)} |"
        )

    lines.extend(
        [
            "",
            "## Table 3. Mean collusion at Z=3.0",
            "",
            "| k | Clean top-1 | VQGAN top-1 | VQGAN detect | VQGAN false | VQGAN abstain | SimSwap top-1 | SimSwap detect | SimSwap false | SimSwap abstain |",
            "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for k in range(2, 6):
        clean_row = vq_collusion["conditions"]["clean"][str(k)]
        vq_row = vq_collusion["conditions"]["VQGAN"][str(k)]
        sim_row = sim_collusion["mixes"]["mean"][str(k)]
        vq_op = vq_row["operating_points"]["3.0"]
        sim_op = sim_row["operating_points"]["3.0"]
        lines.append(
            f"| {k} | {pct(clean_row['top1'], 1)} | {pct(vq_row['top1'], 1)} | "
            f"{pct(vq_op['detect'], 1)} | {pct(vq_op['false_accuse'], 1)} | {pct(vq_op['abstain'], 1)} | "
            f"{pct(sim_row['top1'], 1)} | {pct(sim_op['detect'], 1)} | {pct(sim_op['false_accuse'], 1)} | "
            f"{pct(sim_op['abstain'], 1)} |"
        )

    lines.extend(
        [
            "",
            "## Table 4. SimSwap-224 collusion mixes at Z=3.0",
            "",
            "| Mix | k | Top-1 | Detect | False accusation | Abstain |",
            "|---|---:|---:|---:|---:|---:|",
        ]
    )
    for mix in ("mean", "median", "mosaic"):
        for k in range(2, 6):
            row = sim_collusion["mixes"][mix][str(k)]
            op = row["operating_points"]["3.0"]
            lines.append(
                f"| {mix} | {k} | {pct(row['top1'], 1)} | {pct(op['detect'], 1)} | "
                f"{pct(op['false_accuse'], 1)} | {pct(op['abstain'], 1)} |"
            )

    lines.extend(
        [
            "",
            "## Table 5. Group-wise five-fold threshold calibration",
            "",
            "Calibration targets a 1% false-accusation budget. The reported false-accusation values are out-of-fold estimates, not a strict 1% guarantee.",
            "",
            "| Dataset | k | Threshold median [range] | Clean detect | Attack detect | Attack false | Attack abstain |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for dataset_name, dataset in threshold_cv["datasets"].items():
        for k in range(2, 6):
            row = dataset["k"][str(k)]
            clean_cv = row["clean"]["cross_validated"]
            attack_cv = row["attack"]["cross_validated"]
            lines.append(
                f"| {dataset_name} | {k} | {number(row['fold_threshold_median'], 2)} "
                f"[{threshold_range(row['fold_threshold_range'])}] | {pct(clean_cv['detect'], 1)} | "
                f"{pct(attack_cv['detect'], 1)} | {pct(attack_cv['false_accuse'], 1)} | "
                f"{pct(attack_cv['abstain'], 1)} |"
            )

    lines.extend(
        [
            "",
            "## Table 6. 500-user BCH codebook and candidate-pool scaling",
            "",
            "This experiment uses one image per user. It is not a 500-user multi-image or collusion experiment.",
            "",
            "| Attack | BER | Exact 30-bit | Mean Hamming | Max Hamming | Top-1@500 | Hamming margin | z margin at 500 | Z=3 false |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for name, user_data, scale_data in (
        ("VQGAN", vq_500, vq_scale),
        ("SimSwap-224", sim_500, sim_scale),
        ("InSwapper-128", ins_500, ins_scale),
    ):
        per_image = user_data["per_image"]
        final = user_data["final"]
        scale_500 = scale_data["candidate_sizes"]["500"]
        op = scale_500["operating_points"]["3.0"]
        lines.append(
            f"| {name} | {pct(per_image['ber'], 4)} | {pct(per_image['exact_match'], 1)} | "
            f"{number(per_image['mean_hamming'], 3)} | {int(per_image['max_hamming'])} | "
            f"{pct(final['user_identification_accuracy'], 1)} | {number(final['mean_second_best_margin'], 3)} | "
            f"{number(scale_500['mean_margin'], 3)} | {pct(op['false_accuse'], 1)} |"
        )

    lines.extend(
        [
            "",
            "At 50 and 500 candidate users, Top-1 is 100% under all three attacks; the Z=3 false-accusation rate is 0% in both bins.",
            "",
            "## Table 7. InSwapper-128 collusion pilot (exploratory only)",
            "",
            "This table contains 10 groups per cell. It is a direction-finding pilot and must not be merged with the formal 100-group collusion tables.",
            "",
            "| Mix | k | InSwapper top-1 | Z=3 detect | Z=3 false | Z=3 abstain |",
            "|---|---:|---:|---:|---:|---:|",
        ]
    )
    for mix in ("mean", "median", "mosaic"):
        for k in range(2, 6):
            row = ins_collusion_pilot["mixes"][mix][str(k)]
            op = row["operating_points"]["3.0"]
            lines.append(
                f"| {mix} | {k} | {pct(row['top1'], 1)} | {pct(op['detect'], 1)} | "
                f"{pct(op['false_accuse'], 1)} | {pct(op['abstain'], 1)} |"
            )

    lines.extend(
        [
            "",
            "",
            "## Source artifacts",
            "",
            f"- Clean quality log: `{clean_log.relative_to(ROOT)}`",
            "- `results/user_fingerprint_eval_30k_min11.json`",
            "- `results/user_fingerprint_eval_30k_min11_simswap224_probs.json`",
            "- `results/user_fingerprint_eval_30k_min11_inswapper128_probs.json`",
            "- `results/multimage_llr_summary.json`",
            "- `results/simswap224_multimage_llr_summary.json`",
            "- `results/inswapper128_multimage_llr_summary.json`",
            "- `results/vqgan_collusion_soft_detector_mean_100groups.json`",
            "- `results/simswap224_collusion_mix_summary.json`",
            "- `results/inswapper128_collusion_mix_10groups_exploratory.json`",
            "- `results/collusion_threshold_cv.json`",
            "- `results/user_fingerprint_eval_30k_500users_bch_vqgan_probs.json`",
            "- `results/user_fingerprint_eval_30k_500users_bch_simswap224_probs.json`",
            "- `results/user_fingerprint_eval_30k_500users_bch_inswapper128_probs.json`",
            "- `results/codebook_scaling_500users.json`",
            "- `results/codebook_scaling_500users_simswap224.json`",
            "- `results/codebook_scaling_500users_inswapper128.json`",
            "",
        ]
    )
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--clean_log", type=Path, default=DEFAULT_CLEAN_LOG)
    parser.add_argument("--output", type=Path, default=ROOT / "docs" / "paper_tables.md")
    args = parser.parse_args()

    clean_log = args.clean_log if args.clean_log.is_absolute() else ROOT / args.clean_log
    output = args.output if args.output.is_absolute() else ROOT / args.output
    lines = build_tables(clean_log)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"saved: {output}")


if __name__ == "__main__":
    main()
